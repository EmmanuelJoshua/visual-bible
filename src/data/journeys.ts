import type { EraId } from "./types";

/**
 * Journeys of Scripture, as ordered waypoints for the /journeys map.
 *
 * Coordinates come from the Theographic places dataset (`data/raw/places.json`,
 * slug noted in `place`) wherever it has them; the rest are hand-curated and
 * marked `interpretive` when the site itself is traditional or debated.
 * Years follow the same Ussher-style chronology as `generated/events.json`
 * (negative = BC), so journeys line up with the timeline.
 */

export type LngLat = [lng: number, lat: number];

export type JourneyStop = {
  /** short place name shown on the map, e.g. "Ararat" */
  name: string;
  /** cinematic headline for the stop card */
  title: string;
  coord: LngLat;
  year: number;
  ref: string;
  note: string;
  /** Theographic place slug the coordinate came from */
  place?: string;
  /** genealogy slugs relevant to this stop (falls back to the journey's) */
  people?: string[];
  /** site is traditional / debated rather than certain */
  interpretive?: boolean;
  /** intermediate points on the way from the previous stop (roads, coasts) */
  via?: LngLat[];
  /** time passes / a new chapter: no route drawn from the previous stop */
  newLeg?: boolean;
};

export type Journey = {
  id: string;
  name: string;
  /** compact label for chips on narrow screens */
  short: string;
  subtitle: string;
  era: EraId;
  color: string;
  people: string[];
  /** caveat shown with the whole journey */
  caveat?: string;
  stops: JourneyStop[];
};

